const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
require.extensions['.ts'] = (module, filename) => module._compile(ts.transpileModule(fs.readFileSync(filename, 'utf8'), {compilerOptions: {module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022}}).outputText, filename);
const { sessionKind, mergeSessions, filterSessions } = require('../src/sessionHistory.ts');
const row = (id, source, bot='default', lastActive=1, title=id) => ({id, source, bot, lastActive, title, messageCount:2, archived:false});
assert.equal(sessionKind(row('cron_news_20261031_090000', 'cli')), 'scheduled');
assert.equal(sessionKind(row('x', 'cron')), 'scheduled');
assert.equal(sessionKind(row('news', 'telegram')), 'other');
assert.equal(sessionKind(row('x', 'api-server')), 'chat');
assert.equal(sessionKind(row('x', 'api_server')), 'chat');
assert.equal(sessionKind(row('x', undefined, 'default', 1, 'daily cron news')), 'other');
const first = [row('shared', 'cli'), row('keep', 'cron')];
const merged = mergeSessions(first, [row('shared', 'cli', 'default', 5, 'updated'), row('shared', 'telegram', 'other', 3)]);
assert.equal(merged.length, 3);
assert.equal(merged[0].title, 'updated');
assert.equal(first[0].title, 'shared', 'Do not mutate the previous page');
assert.equal(filterSessions(merged, 'other', 'TELEGRAM')[0].bot, 'other');
assert.equal(filterSessions(merged, 'scheduled', '').length, 1);
assert.equal(filterSessions(merged, 'all', 'updated').length, 1);
console.log('PASS: source filters, cron IDs, unknown sources, page deduplication, ordering and profile isolation');
