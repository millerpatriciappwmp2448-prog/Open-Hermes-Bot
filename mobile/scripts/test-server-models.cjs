const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
require.extensions['.ts'] = (module, filename) => module._compile(ts.transpileModule(fs.readFileSync(filename, 'utf8'), {compilerOptions: {module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022}}).outputText, filename);
const { readModelPick, withModelPick, modelForTurn, modelChoices } = require('../src/modelSelection.ts');
const prefs = { hidden: ['keep'], custom: { untouched: true }, defaults: { default: { model: 'main', provider: 'custom' } }, picks: { worker: { model: 'worker-v2', provider: 'private' } } };
assert.deepEqual(readModelPick(prefs, 'worker'), { model: 'worker-v2', provider: 'private' });
assert.deepEqual(readModelPick(prefs, 'default'), { model: 'main', provider: 'custom' });
assert.equal(readModelPick(prefs, 'other'), undefined, 'One bot must never inherit another bot model pick');
const changed = withModelPick(prefs, 'worker', { model: 'my/model', provider: 'custom' });
assert.deepEqual(changed.picks.worker, { model: 'my/model', provider: 'custom' });
assert.deepEqual(changed.defaults, prefs.defaults);
assert.deepEqual(changed.custom, prefs.custom);
assert.equal(prefs.picks.worker.model, 'worker-v2', 'Do not mutate the server snapshot');
const cleared = withModelPick(prefs, 'default', null);
assert.equal(readModelPick(cleared, 'default'), undefined);
assert.deepEqual(cleared.picks.worker, prefs.picks.worker);
const custom = { current: 'company/model-v1', currentProvider: 'custom', providers: [] };
assert.deepEqual(modelForTurn(undefined, custom), { model: 'company/model-v1', provider: 'custom' });
assert.deepEqual(modelForTurn({ model: 'company/model-v2', provider: 'custom' }, custom), { model: 'company/model-v2', provider: 'custom' });
assert.deepEqual(modelForTurn(undefined, undefined), {}, 'No fabricated demo model if discovery fails');
assert.deepEqual(modelForTurn({ model: 'my/model', provider: '' }, custom), { model: 'my/model' });
assert.equal(modelChoices(custom)[0].model, 'company/model-v1', 'Custom server model stays selectable without an options list');
assert.deepEqual(modelChoices({ ...custom, providers: [{ slug: 'custom', name: 'Private', models: [{ id: 'company/model-v1', name: 'Friendly name' }] }] }), [{ model: 'company/model-v1', provider: 'custom', label: 'Friendly name', providerName: 'Private' }]);
console.log('PASS: per-profile model picks, server preference preservation, custom endpoints, exact model/provider IDs and no demo fallback');
